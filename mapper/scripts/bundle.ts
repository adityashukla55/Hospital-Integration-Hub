/**
 * Bundles the ES5 CommonJS build into one IIFE that defines the global
 * `HubMapper`, ready to be embedded in an OIE code template. esbuild only
 * bundles here: the input is already ES5 (tsc did the downlevelling), and
 * `target: es5` makes esbuild fail if anything newer slipped through.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };
const outfile = join(root, 'dist', 'hub-mapper.js');
mkdirSync(dirname(outfile), { recursive: true });
// build/ holds tsc's CommonJS output while this package is ESM (tests, scripts)
writeFileSync(join(root, 'build', 'package.json'), '{ "type": "commonjs" }\n');

await build({
  entryPoints: [join(root, 'build', 'index.js')],
  outfile,
  bundle: true,
  format: 'iife',
  globalName: 'HubMapper',
  platform: 'neutral',
  target: 'es5',
  charset: 'utf8',
  legalComments: 'none',
  banner: {
    js: `/* @hub/mapper ${pkg.version} - generated by mapper/scripts/bundle.ts, do not edit */`
  }
});

// OIE prepends code templates to channel scripts: a file-level "use strict"
// would silently switch the whole channel script to strict mode.
const code = readFileSync(outfile, 'utf8').replace(/^"use strict";\n/m, '');
if (!/^var HubMapper = /m.test(code)) throw new Error('bundle does not define the HubMapper global');
writeFileSync(outfile, code, 'utf8');
console.log(`wrote ${outfile} (${(code.length / 1024).toFixed(1)} KiB)`);
